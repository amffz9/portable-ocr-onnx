#!/usr/bin/env python3
"""Generate golden reference outputs from the PyTorch pipeline (CPU, FP32).

For every test image and variant this runs ``NemotronOCRV2`` and records the inputs
and outputs of each network plus the final predictions:

    tests/golden/manifest.json                     environment + per-image summary
    tests/golden/<variant>/<image>.json            final predictions (word/sentence/paragraph)
    tests/golden/<variant>/<image>.npz             compact tensors (committed)
    tests/golden_full/<variant>/<image>.npz        every network tensor in full (--full, gitignored)

Compact tensors keep small arrays whole (NMS quads, recognizer ids/probs,
relational matrices, rectification grids for the relational model) and store
fixed-stride subsamples of the large ones (detector input/features, recognizer
input/features). Key names ending in ``__s<k>...`` record the stride; see
``COMPACT_SPEC``. The full set is what M3 compares exported graphs against; it is
regenerated by running this script with ``--full``.

Usage:
    scripts/make_golden.py [--variants english multilingual] [--full] [--images a.png ...]
"""

import argparse
import json
import platform
import sys
import time
import warnings
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from nemotron_ocr.inference.pipeline_v2 import NemotronOCRV2  # noqa: E402

MERGE_LEVELS = ("word", "sentence", "paragraph")

# name -> slices applied to the full tensor for the compact (committed) set.
# None = keep whole.
COMPACT_SPEC = {
    "det_input": (slice(None), slice(None), slice(None, None, 16), slice(None, None, 16)),
    "det_conf": (slice(None), slice(None, None, 2), slice(None, None, 2)),
    "det_rboxes": (slice(None), slice(None, None, 4), slice(None, None, 4)),
    "det_features": (slice(None), slice(None, None, 8), slice(None, None, 8), slice(None, None, 8)),
    "nms_quads": None,
    "nms_confidence": None,
    "region_counts": None,
    "rec_grid": (slice(None), slice(None), slice(None, None, 4)),
    "rec_input": (slice(None), slice(None, None, 16), slice(None), slice(None, None, 4)),
    "rec_ids": None,
    "rec_probs": None,
    "rec_logit_max": None,
    "rec_logsumexp": None,
    "rec_features": (slice(None), slice(None, None, 4), slice(None, None, 16)),
    "rel_grid": None,
    "rel_input": (slice(None), slice(None, None, 4)),
    "rel_words": None,
    "rel_lines": None,
    "rel_line_var": None,
}

# Full logits are huge for the multilingual vocabulary ([N, 128, 14247] fp32); the
# full set keeps them for the first FULL_LOGIT_REGIONS regions only.
FULL_LOGIT_REGIONS = 16


def stride_tag(spec):
    if spec is None:
        return ""
    steps = [s.step or 1 for s in spec]
    return "__s" + "x".join(str(s) for s in steps)


class Recorder:
    """Wraps a NemotronOCRV2 instance to capture network I/O for one call."""

    def __init__(self, ocr: NemotronOCRV2):
        self.ocr = ocr
        self.t = {}
        self._grid_calls = 0
        self._rec_in, self._rec_logits, self._rec_feats = [], [], []
        self.enabled = False

        ocr.detector.register_forward_hook(self._det_hook)
        ocr.recognizer.register_forward_hook(self._rec_hook)
        ocr.relational.register_forward_hook(self._rel_hook)
        ocr.grid_sampler.register_forward_hook(self._grid_hook)

        orig_pre = ocr._preprocess_batch
        orig_nms = ocr._run_nms
        orig_recog = ocr._run_recognizer_chunked

        def pre(images, timings=None):
            out = orig_pre(images, timings)
            if self.enabled:
                self.t["det_input"] = out[0].detach().clone()
                self.meta = {"original_shapes": out[1], "padded_lengths": out[2]}
            return out

        def nms(det_conf, det_rboxes):
            out = orig_nms(det_conf, det_rboxes)
            if self.enabled and out is not None:
                quads, conf, counts, _ = out
                self.t["nms_quads"] = quads.detach().clone()
                self.t["nms_confidence"] = conf.detach().clone()
                self.t["region_counts"] = counts.detach().clone()
            return out

        def recog(rec_quads):
            ids, probs, feats = orig_recog(rec_quads)
            if self.enabled:
                self.t["rec_ids"] = ids.detach().clone()
                self.t["rec_probs"] = probs.detach().clone()
            return ids, probs, feats

        ocr._preprocess_batch = pre
        ocr._run_nms = nms
        ocr._run_recognizer_chunked = recog

    def _det_hook(self, m, args, out):
        if self.enabled:
            self.t["det_conf"] = out[0].detach().clone()
            self.t["det_rboxes"] = out[2].detach().clone()
            self.t["det_features"] = out[3].detach().clone()

    def _grid_hook(self, m, args, out):
        if not self.enabled:
            return
        _, grid, idx = args
        name = "rec" if self._grid_calls == 0 else "rel"
        self._grid_calls += 1
        self.t[f"{name}_grid"] = grid.detach().clone()
        self.t[f"{name}_input"] = out.detach().clone()
        self.t["input_indices"] = idx.detach().clone()

    def _rec_hook(self, m, args, out):
        if self.enabled:
            self._rec_in.append(args[0].detach().clone())
            self._rec_logits.append(out[0].detach().clone())
            self._rec_feats.append(out[1].detach().clone())

    def _rel_hook(self, m, args, out):
        if self.enabled:
            assert len(out["words"]) == 1, "golden capture runs one image at a time"
            self.t["rel_words"] = out["words"][0].detach().clone()
            self.t["rel_lines"] = out["lines"][0].detach().clone()
            self.t["rel_line_var"] = out["line_log_var_unc"][0].detach().clone()

    def run(self, image_path):
        self.t, self.meta, self._grid_calls = {}, {}, 0
        self._rec_in, self._rec_logits, self._rec_feats = [], [], []
        preds = {}
        self.enabled = True
        try:
            preds["paragraph"] = self.ocr(str(image_path), merge_level="paragraph")
        finally:
            self.enabled = False
        for lvl in MERGE_LEVELS:
            if lvl not in preds:
                preds[lvl] = self.ocr(str(image_path), merge_level=lvl)

        n = int(self.t["nms_quads"].shape[0]) if "nms_quads" in self.t else 0
        if self._rec_in:
            real_tokens = self.ocr.recognizer_real_num_tokens
            self.t["rec_input"] = torch.cat(self._rec_in)[:n]
            logits = torch.cat(self._rec_logits)[:n, :, :real_tokens]
            self.t["rec_logits"] = logits[:FULL_LOGIT_REGIONS]
            self.t["rec_logit_max"] = logits.max(dim=2).values
            self.t["rec_logsumexp"] = logits.logsumexp(dim=2)
            self.t["rec_features"] = torch.cat(self._rec_feats)[:n]
            assert torch.isfinite(self.t["rec_input"]).all(), "non-finite recognizer input"
        return preds, n


def to_np(x):
    if torch.is_tensor(x):
        x = x.detach().cpu()
        if x.dtype == torch.int64:
            return x.numpy()
        return x.float().numpy() if x.is_floating_point() else x.numpy()
    return np.asarray(x)


def compact(tensors):
    out = {}
    for name, spec in COMPACT_SPEC.items():
        if name not in tensors:
            continue
        a = to_np(tensors[name])
        if spec is not None:
            a = a[spec[: a.ndim]]
        if name == "rec_ids":
            a = a.astype(np.int32)
        out[name + stride_tag(spec)] = np.ascontiguousarray(a)
    return out


def predictions_px(preds, orig_hw):
    """Add pixel-space boxes so comparisons can use a px tolerance."""
    h, w = orig_hw
    out = []
    for p in preds:
        q = dict(p)
        q["box_px"] = [p["left"] * w, p["lower"] * h, p["right"] * w, p["upper"] * h]
        out.append(q)
    return out


def default_images():
    imgs = sorted((ROOT / "tests" / "images").glob("*.png"))
    sample = ROOT / "weights" / "ocr-example-input-1.png"
    if sample.exists():
        imgs = [sample] + imgs
    else:
        print(f"note: {sample} not found (run scripts/fetch_weights.sh); skipping upstream sample")
    return imgs


def image_key(path: Path) -> str:
    return "sample" if path.name == "ocr-example-input-1.png" else path.stem


def main():
    ap = argparse.ArgumentParser(description="Generate golden reference outputs.")
    ap.add_argument("--variants", nargs="+", default=["english", "multilingual"],
                    choices=["english", "multilingual"])
    ap.add_argument("--images", nargs="*", type=Path, default=None)
    ap.add_argument("--weights", type=Path, default=ROOT / "weights")
    ap.add_argument("--out", type=Path, default=ROOT / "tests" / "golden")
    ap.add_argument("--full", action="store_true", help="also write full tensors to tests/golden_full")
    ap.add_argument("--full-out", type=Path, default=ROOT / "tests" / "golden_full")
    args = ap.parse_args()

    warnings.filterwarnings("ignore", message="enable_nested_tensor")
    torch.manual_seed(0)
    images = args.images or default_images()

    manifest_path = args.out / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {"variants": {}}
    manifest["environment"] = {
        "python": platform.python_version(),
        "platform": platform.platform(),
        "machine": platform.machine(),
        "torch": torch.__version__,
        "numpy": np.__version__,
        "device": "cpu",
        "precision": "fp32",
        "threads": torch.get_num_threads(),
    }
    manifest["merge_levels"] = list(MERGE_LEVELS)
    manifest["compact_spec"] = {k: stride_tag(v) or "full" for k, v in COMPACT_SPEC.items()}

    for variant in args.variants:
        ocr = NemotronOCRV2(model_dir=str(args.weights / f"v2_{variant}"), device="cpu", precision="fp32")
        ocr.recognizer_real_num_tokens = ocr.num_tokens
        rec = Recorder(ocr)
        vdir = args.out / variant
        vdir.mkdir(parents=True, exist_ok=True)
        entries = manifest["variants"].setdefault(variant, {})

        for img in images:
            key = image_key(img)
            t0 = time.perf_counter()
            preds, n = rec.run(img)
            dt = time.perf_counter() - t0
            orig_hw = rec.meta["original_shapes"][0]

            pred_doc = {
                "image": str(img.relative_to(ROOT)) if img.is_relative_to(ROOT) else str(img),
                "variant": variant,
                "original_hw": list(orig_hw),
                "padded_length": rec.meta["padded_lengths"][0],
                "num_regions": n,
                "predictions": {lvl: predictions_px(preds[lvl], orig_hw) for lvl in MERGE_LEVELS},
            }
            (vdir / f"{key}.json").write_text(json.dumps(pred_doc, indent=1, ensure_ascii=False))
            np.savez_compressed(vdir / f"{key}.npz", **compact(rec.t))

            if args.full:
                fdir = args.full_out / variant
                fdir.mkdir(parents=True, exist_ok=True)
                np.savez(fdir / f"{key}.npz", **{k: to_np(v) for k, v in rec.t.items()})

            entries[key] = {
                "image": pred_doc["image"],
                "num_regions": n,
                "num_paragraphs": len(preds["paragraph"]),
                "seconds": round(dt, 2),
            }
            print(f"[{variant}] {key:14s} regions={n:4d} paragraphs={len(preds['paragraph']):3d} {dt:6.1f}s")

        del ocr, rec

    manifest_path.write_text(json.dumps(manifest, indent=1, sort_keys=True))
    size = sum(p.stat().st_size for p in args.out.rglob("*") if p.is_file())
    print(f"golden set: {size / 1e6:.1f} MB in {args.out}")


if __name__ == "__main__":
    main()
